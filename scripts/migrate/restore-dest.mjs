#!/usr/bin/env node
/**
 * Restore data.dump onto Zurich. WRITES to destination — guarded.
 *
 * Does NOT use pg_restore --disable-triggers (postgres is not superuser).
 * Instead: pg_restore → SQL file, prepend SET session_replication_role = replica,
 * apply with psql -1 (single transaction) ON_ERROR_STOP=1.
 *
 * Usage:
 *   node scripts/migrate/restore-dest.mjs --dry-run
 *   node scripts/migrate/restore-dest.mjs --apply
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import {
  assertPgTools,
  assertSafeDest,
  ensureRunDir,
  maskDbUrl,
  parseArgs,
  requireEnv,
  run,
  timedSync,
} from './lib-db.mjs';

const truncateSql = `
BEGIN;
SET session_replication_role = replica;
DO $body$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT format('%I.%I', n.nspname, c.relname) AS fq
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r'
  LOOP
    EXECUTE 'TRUNCATE TABLE ' || r.fq || ' CASCADE';
  END LOOP;
END
$body$;
TRUNCATE TABLE auth.users CASCADE;
COMMIT;
`;

const sequencesSql = `
DO $body$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT quote_ident(n.nspname) || '.' || quote_ident(c.relname) AS tbl,
           quote_ident(a.attname) AS col,
           pg_get_serial_sequence(
             quote_ident(n.nspname) || '.' || quote_ident(c.relname),
             a.attname
           ) AS seq
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
    WHERE n.nspname = 'public'
      AND c.relkind = 'r'
      AND pg_get_serial_sequence(
            quote_ident(n.nspname) || '.' || quote_ident(c.relname),
            a.attname
          ) IS NOT NULL
  LOOP
    EXECUTE format(
      'SELECT setval(%L, coalesce((SELECT max(%s) FROM %s), 1), true)',
      r.seq, r.col, r.tbl
    );
  END LOOP;
END
$body$;
`;

/** Build SQL file: SET replica + pg_restore --data-only plain SQL. */
export function buildRestoreSqlFile(pgRestoreBin, dumpPath, outSqlPath, { dryRun = false } = {}) {
  const header =
    `-- generated by restore-dest.mjs — do not commit\n` +
    `SET session_replication_role = replica;\n\n`;

  if (dryRun) {
    console.log(
      `[dry-run] pg_restore --data-only --no-owner -f ${outSqlPath} ${dumpPath}`
    );
    console.log(`[dry-run] prepend: SET session_replication_role = replica;`);
    console.log(`[dry-run] psql -1 -v ON_ERROR_STOP=1 -f ${outSqlPath}`);
    return;
  }

  run(
    pgRestoreBin,
    ['--data-only', '--no-owner', '-f', outSqlPath, dumpPath],
    { label: 'pg_restore → SQL' }
  );
  const body = fs.readFileSync(outSqlPath, 'utf8');
  fs.writeFileSync(outSqlPath, header + body, 'utf8');
}

function main() {
  const { dryRun, help, flags } = parseArgs();
  const apply = flags.has('apply');
  const effectiveDryRun = dryRun || !apply;

  if (help) {
    console.log(`Usage:
  node scripts/migrate/restore-dest.mjs --dry-run
  node scripts/migrate/restore-dest.mjs --apply

Aborts if dest is not Zurich, is Ireland, or equals source.
Requires --apply for any write.`);
    process.exit(0);
  }

  const sourceUrl = process.env.MIGRATE_SOURCE_DB_URL || '';
  const destUrl = effectiveDryRun
    ? process.env.MIGRATE_DEST_DB_URL || ''
    : requireEnv('MIGRATE_DEST_DB_URL');

  console.log(`Source: ${maskDbUrl(sourceUrl)}`);
  console.log(`Dest:   ${maskDbUrl(destUrl)}`);

  if (destUrl) {
    try {
      assertSafeDest(destUrl, sourceUrl);
      console.log('Dest host guards: OK');
    } catch (e) {
      console.error(String(e.message || e));
      process.exit(1);
    }
  } else if (!effectiveDryRun) {
    console.error('Missing MIGRATE_DEST_DB_URL');
    process.exit(1);
  } else {
    console.log(
      '[dry-run] MIGRATE_DEST_DB_URL unset — would still enforce Zurich host guards before write'
    );
  }

  const runDir = ensureRunDir(process.env.MIGRATE_DUMP_DIR);
  const dataFile = path.join(runDir, 'data.dump');
  const dataSqlFile = path.join(runDir, 'data-restore.sql');

  timedSync('restore-dest', () => {
    if (!effectiveDryRun && !fs.existsSync(dataFile)) {
      throw new Error(`Missing ${dataFile}`);
    }

    console.log('Plan:');
    console.log('  1. assertSafeDest (Zurich only)');
    console.log('  2. TRUNCATE public.* CASCADE + auth.users CASCADE (with session_replication_role=replica)');
    console.log('  3. pg_restore --data-only --no-owner -f data-restore.sql (NO --disable-triggers)');
    console.log('  4. prepend SET session_replication_role = replica;');
    console.log('  5. psql -1 -v ON_ERROR_STOP=1 -f data-restore.sql');
    console.log('  6. Realign sequences; ANALYZE');
    console.log('  Note: apply baseline_zurich.sql once before the first data restore.');

    if (effectiveDryRun) {
      console.log('[dry-run] no write to destination');
      buildRestoreSqlFile('pg_restore', dataFile, dataSqlFile, { dryRun: true });
      console.log(
        `[dry-run] would truncate + apply on ${maskDbUrl(destUrl || 'MIGRATE_DEST_DB_URL')}`
      );
      return;
    }

    const tools = assertPgTools();

    // Probe privilege for session_replication_role before truncating data away
    try {
      run(
        tools.psql.bin,
        [
          '-v',
          'ON_ERROR_STOP=1',
          '-c',
          'SET session_replication_role = replica; SET session_replication_role = origin;',
          destUrl,
        ],
        { label: 'probe session_replication_role' }
      );
    } catch (e) {
      const detail = String(e.message || e);
      throw new Error(
        'Cannot SET session_replication_role = replica on destination. ' +
          'Restore needs this privilege (Supabase postgres role) because --disable-triggers ' +
          'is unavailable without superuser. Aborting before TRUNCATE. ' +
          `Details: ${detail}`
      );
    }

    run(tools.psql.bin, ['-v', 'ON_ERROR_STOP=1', '-c', truncateSql, destUrl], {
      label: 'truncate dest',
    });

    buildRestoreSqlFile(tools.pg_restore.bin, dataFile, dataSqlFile, { dryRun: false });

    run(
      tools.psql.bin,
      ['-1', '-v', 'ON_ERROR_STOP=1', '-f', dataSqlFile, destUrl],
      { label: 'psql apply data-restore.sql' }
    );

    run(tools.psql.bin, ['-v', 'ON_ERROR_STOP=1', '-c', sequencesSql, destUrl], {
      label: 'realign sequences',
    });

    run(tools.psql.bin, ['-v', 'ON_ERROR_STOP=1', '-c', 'ANALYZE;', destUrl], {
      label: 'ANALYZE',
    });

    console.log('Restore finished. Run verify-counts.mjs next.');
  });
}

const isMain =
  process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (isMain) main();
